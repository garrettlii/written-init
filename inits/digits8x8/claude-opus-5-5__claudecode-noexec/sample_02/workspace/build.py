SCALE = 10.0   # score = SCALE * <x, w>, |<x,w>| <= ||x - mean(x)|| <= 8
SHIFT = 100.0  # keeps "pass-through" units strictly positive


def _parse(rows):
    t = np.zeros((8, 8))
    for r in range(8):
        row = (rows[r] if r < len(rows) else "").ljust(8, ".")[:8]
        for c, ch in enumerate(row):
            if ch.isdigit():
                t[r, c] = int(ch) / 9.0
    return t


def _blur(t):
    k = np.array([[0.25, 0.5, 0.25], [0.5, 1.0, 0.5], [0.25, 0.5, 0.25]])
    p = np.pad(t, 1)
    out = np.zeros_like(t)
    for dr in range(3):
        for dc in range(3):
            out += k[dr, dc] * p[dr:dr + 8, dc:dc + 8]
    return out


def _filter(rows):
    t = _blur(_parse(rows)).reshape(64)
    t = t - t.mean()
    return t / np.linalg.norm(t)


def build_weights():
    W0 = np.zeros((64, 64)); b0 = np.zeros(64)
    W1 = np.zeros((64, 32)); b1 = np.zeros(32)
    W2 = np.zeros((32, 10)); b2 = np.zeros(10)

    for k in range(10):
        fs = [_filter(t) for t in TEMPLATES[k]]
        while len(fs) < 4:
            fs.append(fs[len(fs) % len(TEMPLATES[k])])
        a, b, c, d = [SCALE * f for f in fs[:4]]
        u = 4 * k
        # layer 1: relu(a-b), b+C, relu(c-d), d+C
        W0[:, u + 0] = a - b
        W0[:, u + 1] = b; b0[u + 1] = SHIFT
        W0[:, u + 2] = c - d
        W0[:, u + 3] = d; b0[u + 3] = SHIFT
        # layer 2: m1 = max(a,b)+C, m2 = max(c,d)+C
        v = 2 * k
        W1[u + 0, v] = 1; W1[u + 1, v] = 1
        W1[u + 2, v] = -1; W1[u + 3, v] = -1      # relu(m1 - m2)
        W1[u + 2, v + 1] = 1; W1[u + 3, v + 1] = 1  # relu(m2)
        # output: max(m1, m2) = relu(m1-m2) + m2
        W2[v, k] = 1; W2[v + 1, k] = 1

    return {"W0": W0, "b0": b0, "W1": W1, "b1": b1, "W2": W2, "b2": b2}
