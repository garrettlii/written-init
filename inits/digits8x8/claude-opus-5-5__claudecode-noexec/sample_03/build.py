VAL = {'#': 1.0, '+': 0.5}


def _parse(s):
    rows = [r for r in s.strip("\n").split("\n")]
    img = np.zeros((8, 8))
    for r in range(min(8, len(rows))):
        line = rows[r].strip()
        for c in range(min(8, len(line))):
            img[r, c] = VAL.get(line[c], 0.0)
    return img


def _blur(img):
    # soften thin hand-drawn strokes to resemble the thick, smooth 8x8 strokes
    out = img.copy()
    p = np.pad(img, 1)
    orth = p[:-2, 1:-1] + p[2:, 1:-1] + p[1:-1, :-2] + p[1:-1, 2:]
    diag = p[:-2, :-2] + p[:-2, 2:] + p[2:, :-2] + p[2:, 2:]
    out = out + 0.3 * orth + 0.1 * diag
    return np.clip(out, 0.0, 1.0)


def build_weights():
    C = 40.0  # offset keeping "pass-through" units positive (|s| <= 32)
    W0 = np.zeros((64, 64)); b0 = np.zeros(64)
    W1 = np.zeros((64, 32)); b1 = np.zeros(32)
    W2 = np.zeros((32, 10)); b2 = np.zeros(10)

    for k in range(10):
        ws, bs = [], []
        for s in P[k]:
            T = _blur(_parse(s)).reshape(64)
            ws.append(T)
            bs.append(-0.5 * float(T @ T))
        base = 4 * k
        # layer 0: u0 = s0 + C, u1 = relu(s1 - s0), u2 = s2 + C, u3 = relu(s3 - s2)
        W0[:, base + 0] = ws[0]; b0[base + 0] = bs[0] + C
        W0[:, base + 1] = ws[1] - ws[0]; b0[base + 1] = bs[1] - bs[0]
        W0[:, base + 2] = ws[2]; b0[base + 2] = bs[2] + C
        W0[:, base + 3] = ws[3] - ws[2]; b0[base + 3] = bs[3] - bs[2]
        # layer 1: v0 = m01 = max(s0,s1)+C ; v1 = relu(m23 - m01)
        j = 2 * k
        W1[base + 0, j] = 1.0; W1[base + 1, j] = 1.0
        W1[base + 2, j + 1] = 1.0; W1[base + 3, j + 1] = 1.0
        W1[base + 0, j + 1] = -1.0; W1[base + 1, j + 1] = -1.0
        # output: logit = v0 + v1 = max over the 4 prototypes (+C)
        W2[j, k] = 1.0; W2[j + 1, k] = 1.0

    return {"W0": W0, "b0": b0, "W1": W1, "b1": b1, "W2": W2, "b2": b2}
