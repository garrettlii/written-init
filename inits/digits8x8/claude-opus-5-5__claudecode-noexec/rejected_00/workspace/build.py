def parse(rows):
    img = np.zeros((8, 8))
    for r in range(8):
        row = (rows[r] + "........")[:8]
        for c, ch in enumerate(row):
            img[r, c] = 0.0 if ch == "." else int(ch) / 9.0
    return img.reshape(64)


def blur_matrix():
    # Mild 3x3 blur (center .5, orthogonal .1, diagonal .025), zero padding.
    k = {(0, 0): 0.5}
    for d in [(-1, 0), (1, 0), (0, -1), (0, 1)]:
        k[d] = 0.1
    for d in [(-1, -1), (-1, 1), (1, -1), (1, 1)]:
        k[d] = 0.025
    B = np.zeros((64, 64))
    for r in range(8):
        for c in range(8):
            for (dr, dc), v in k.items():
                rr, cc = r + dr, c + dc
                if 0 <= rr < 8 and 0 <= cc < 8:
                    B[r * 8 + c, rr * 8 + cc] = v
    return B


def build_weights():
    B = blur_matrix()
    M = B.T @ B
    C = 100.0  # offset keeping prototype scores positive (|score| <= 64)

    W0 = np.zeros((64, 64)); b0 = np.zeros(64)
    W1 = np.zeros((64, 32)); b1 = np.zeros(32)
    W2 = np.zeros((32, 10)); b2 = np.zeros(10)

    def score(T):
        # score(x) = 2 Bx.BT - |BT|^2 = |Bx|^2 - |Bx - BT|^2
        return 2.0 * (M @ T), -float(T @ M @ T)

    for k in range(10):
        ps = [parse(p) for p in PROTOS[k]]
        if len(ps) == 2:
            ps = [ps[0], ps[1], ps[0], ps[1]]
        elif len(ps) == 3:
            ps = ps + [ps[2]]
        (wa, ba), (wb, bb), (wc, bc), (wd, bd) = [score(T) for T in ps]
        u = 4 * k
        # u0 = s_a + C ; u1 = relu(s_b - s_a) ; u2 = s_c + C ; u3 = relu(s_d - s_c)
        W0[:, u] = wa; b0[u] = ba + C
        W0[:, u + 1] = wb - wa; b0[u + 1] = bb - ba
        W0[:, u + 2] = wc; b0[u + 2] = bc + C
        W0[:, u + 3] = wd - wc; b0[u + 3] = bd - bc
        v = 2 * k
        # v0 = max(s_a, s_b) + C ; v1 = relu(max(s_c,s_d) - max(s_a,s_b))
        W1[u, v] = 1.0; W1[u + 1, v] = 1.0
        W1[u + 2, v + 1] = 1.0; W1[u + 3, v + 1] = 1.0
        W1[u, v + 1] = -1.0; W1[u + 1, v + 1] = -1.0
        # logit_k = max over the 4 prototypes (+C)
        W2[v, k] = 1.0; W2[v + 1, k] = 1.0

    return {"W0": W0, "b0": b0, "W1": W1, "b1": b1, "W2": W2, "b2": b2}
